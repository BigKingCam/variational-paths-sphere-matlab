function export_horizontal_legend(figuresDir)
%EXPORT_HORIZONTAL_LEGEND Export a standalone horizontal legend PNG.
%   Creates a white-background image containing only the legend:
%   Geodesic | Brachistochrone | Least Action
%  >> export_horizontal_legend(fullfile(fileparts(mfilename('fullpath')), '10 results', 'figures'))

%% Export settings

exportWidth  = 11;    % inches  (increase for more horizontal spacing)
exportHeight = 0.9;   % inches
dpi          = 300;

curveWidth = 3.5;
fontSize   = 18;

%% Match plot_sphere_curves.m colors

color_G  = [0.05 0.48 0.25];
color_B  = [0.00 0.32 0.80];
color_LA = [0.82 0.12 0.12];

%% Create temporary figure

fig = figure( ...
    'Visible','off', ...
    'WindowStyle','normal', ...
    'Color','w', ...
    'InvertHardcopy','off', ...
    'Units','inches', ...
    'Position',[1 1 exportWidth exportHeight]);

set(fig,'Theme','Light');

%% Create invisible axes that fills the figure

ax = axes( ...
    'Parent',fig, ...
    'Units','normalized', ...
    'Position',[0 0 1 1], ...
    'Color','w', ...
    'Visible','off', ...
    'XColor','w', ...
    'YColor','w');

hold(ax,'on');
axis(ax,'off');
xlim(ax,[0 1]);
ylim(ax,[0 1]);

%% Dummy lines for legend entries

hG = plot(ax,NaN,NaN, ...
    'Color',color_G, ...
    'LineWidth',curveWidth, ...
    'DisplayName','Geodesic');

hB = plot(ax,NaN,NaN, ...
    'Color',color_B, ...
    'LineWidth',curveWidth, ...
    'DisplayName','Brachistochrone');

hLA = plot(ax,NaN,NaN, ...
    'Color',color_LA, ...
    'LineWidth',curveWidth, ...
    'DisplayName','Least Action');

%% Horizontal legend

hLeg = legend(ax,[hG hB hLA], ...
    {'Geodesic\qquad\qquad', ...
     'Brachistochrone\qquad\qquad', ...
     'Least Action'}, ...
    'Orientation','horizontal', ...
    'NumColumns',3, ...
    'Interpreter','latex', ...
    'FontSize',fontSize, ...
    'Box','off', ...
    'Location','northwest', ...
    'AutoUpdate','off');

% Make sure legend itself is white and clean
hLeg.Color = 'w';
hLeg.EdgeColor = 'none';
hLeg.TextColor = [0 0 0];

% Increase the colored line token length slightly
hLeg.ItemTokenSize = [55, 18];

% Position legend to use almost the entire canvas
hLeg.Units = 'normalized';
hLeg.Position = [0.02 0.08 0.96 0.84];

%% Export

if ~isfolder(figuresDir)
    mkdir(figuresDir);
end

drawnow;

exportgraphics(fig, ...
    fullfile(figuresDir,'legend_horizontal.png'), ...
    'Resolution',dpi, ...
    'BackgroundColor','white', ...
    'Padding','tight');

close(fig);

end